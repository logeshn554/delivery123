import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const source = path.resolve(process.argv[2] || '../stitch-reference/stitch_on_demand_delivery_app_ui');
const output = 'docs/audit/stitch-2026-10-13';
fs.mkdirSync(output, { recursive: true });
const names = fs.readdirSync(source, {withFileTypes:true}).filter(entry=>entry.isDirectory()).map(entry=>entry.name);
const files = names.flatMap(name=>fs.readdirSync(path.join(source,name)).map(file=>{
  const bytes=fs.readFileSync(path.join(source,name,file));
  return { file:`${name}/${file}`,bytes:bytes.length,sha256:crypto.createHash('sha256').update(bytes).digest('hex') };
}));
fs.writeFileSync(`${output}/inventory.json`,JSON.stringify({archive:'stitch_on_demand_delivery_app_ui.zip',files},null,2));
const html=fs.readFileSync(path.join(source,'1._splash_screen/code.html'),'utf8');
const illustration=[...html.matchAll(/<svg\b[\s\S]*?<\/svg>/g)].map(match=>match[0]).find(svg=>/viewBox="0 0 400 300"/.test(svg));
if (!illustration || /<script|foreignObject|\bon\w+\s*=|(?:href|src)\s*=/i.test(illustration)) throw new Error('Welcome vector missing or contains unsafe/external content');
fs.mkdirSync('public/illustrations',{recursive:true});
fs.writeFileSync('public/illustrations/allgo-riders.svg',illustration.replace(/ class="[^"]*"/g,''));
const transportHtml=fs.readFileSync(path.join(source,'14._bike_transport/code.html'),'utf8');
const bike=[...transportHtml.matchAll(/<svg\b[\s\S]*?<\/svg>/g)].map(match=>match[0]).find(svg=>/aria-label="Sports Motorcycle"/.test(svg));
if(!bike || /<script|foreignObject|\bon\w+\s*=|(?:href|src)\s*=/i.test(bike))throw new Error('Transport vector missing or unsafe');
fs.writeFileSync('public/illustrations/allgo-motorbike.svg',bike.replace(/ class="[^"]*"/g,''));
console.log(`Inventoried ${files.length} files from ${names.length-1} screens; imported the supplied inline rider illustration. No screenshot, brand logo or remote photo copied.`);
